// Writes assets/tokens.css from tools/theme/theme.json. Every color and font the site uses
// comes from these custom properties, so a new brand only touches theme.json.
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '../..');
export const theme = JSON.parse(fs.readFileSync(path.join(import.meta.dirname, 'theme.json'), 'utf8'));

// "r, g, b" of a hex color, for translucent shadows and tints: rgba(var(--shadow-rgb), .1)
export const rgb = (hex) => { const h = hex.replace('#', '').slice(0, 6); return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16)).join(', '); };
// Values derived from the theme that the CSS needs but the brand does not name.
export const derived = (mode) => {
  const t = theme[mode];
  return { 'shadow-rgb': mode === 'light' ? rgb(t.ink) : '0, 0, 0', 'ink-rgb': rgb(t.ink), 'signal-rgb': rgb(t.signal) };
};

export function writeTokensCss() {
  const vars = (o) => Object.entries(o).map(([k, v]) => `  --${k}: ${v};`).join('\n');
  const L = { ...theme.light, ...derived('light') }, D = { ...theme.dark, ...derived('dark') };
  const css = `/* Generated by tools/theme/tokens.mjs from tools/theme/theme.json (${theme.name}). Do not edit by hand. */
:root {
${vars(L)}
  --sans: ${theme.fonts.sans};
  --mono: ${theme.fonts.mono};
  --ease: ${theme.motion.ease};
  --ease-exit: ${theme.motion.exit};
  color-scheme: light;
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${vars(D).replace(/^/gm, '  ')}
    color-scheme: dark;
  }
}
:root[data-theme="dark"] {
${vars(D)}
  color-scheme: dark;
}
`;
  fs.writeFileSync(path.join(ROOT, 'assets/tokens.css'), css);
}

if (import.meta.url === `file://${process.argv[1]}`) { writeTokensCss(); console.log('wrote assets/tokens.css'); }
