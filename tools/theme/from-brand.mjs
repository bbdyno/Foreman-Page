// Builds tools/theme/theme.json from the Foreman brand tokens (Foreman/docs/design/tokens.json).
//   node theme/from-brand.mjs [path/to/tokens.json]
// The brand repository is only read. Every site color comes from a semantic token there.
import fs from 'node:fs';
import path from 'node:path';

const src = process.argv[2] || path.resolve(import.meta.dirname, '../../../Foreman/docs/design/tokens.json');
const t = JSON.parse(fs.readFileSync(src, 'utf8'));
const sem = t.semantic;

// site variable  <- brand semantic token
const MAP = {
  paper: 'background', panel: 'surface', 'panel-2': 'surfaceSunken', fill: 'fill',
  ink: 'textPrimary', 'ink-2': 'textSecondary', mute: 'textTertiary',
  rule: 'separator', 'rule-strong': 'separatorStrong',
  accent: 'accent', 'accent-text': 'accentText', 'on-accent': 'onAccent', 'accent-container': 'accentContainer', 'on-accent-container': 'onAccentContainer',
  focus: 'focusRing',
  signal: 'attention', 'on-signal': 'onAttention', 'signal-text': 'attentionText', 'signal-container': 'attentionContainer', 'on-signal-container': 'onAttentionContainer',
  running: 'running', 'running-text': 'runningText',
  success: 'success', 'success-text': 'successText', danger: 'danger', 'danger-text': 'dangerText',
  'code-bg': 'terminalBackground', 'code-fg': 'terminalText', 'code-dim': 'terminalDim',
};
const side = (mode) => {
  const o = {};
  for (const [k, v] of Object.entries(MAP)) {
    if (!sem[v]) throw new Error(`token ${v} missing in ${src}`);
    o[k] = sem[v][mode];
  }
  o['shot-edge'] = mode === 'light' ? 'rgba(11,15,25,.10)' : 'rgba(237,240,245,.10)';
  return o;
};

const theme = {
  name: `${t.name} ${t.version}`,
  source: `Generated by tools/theme/from-brand.mjs from Foreman/docs/design/tokens.json (${t.generated}).`,
  light: side('light'),
  dark: side('dark'),
  fonts: {
    sans: '"Pretendard Variable", Pretendard, -apple-system, BlinkMacSystemFont, system-ui, sans-serif',
    mono: '"JetBrains Mono Variable", "JetBrains Mono", ui-monospace, "SF Mono", Menlo, monospace',
  },
  motion: { ease: t.motion.easeStandard, exit: t.motion.easeExit, short: t.motion.durationShort, medium: t.motion.durationMedium },
};
fs.writeFileSync(path.join(import.meta.dirname, 'theme.json'), JSON.stringify(theme, null, 2) + '\n');
console.log('wrote theme.json from', theme.name);
