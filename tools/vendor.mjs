// Copies third-party assets (fonts, Phosphor icons) from node_modules into ../assets.
// Run after `npm install`. Versions are pinned in package.json; see ../CREDITS.md.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const nm = path.join(import.meta.dirname, 'node_modules');
const out = (...p) => path.join(root, 'assets', ...p);
const mkdir = (d) => fs.mkdirSync(d, { recursive: true });

// Fonts -----------------------------------------------------------------
fs.rmSync(out('fonts'), { recursive: true, force: true });
mkdir(out('fonts/pretendard'));
const pre = path.join(nm, 'pretendard/dist/web/variable');
fs.copyFileSync(path.join(nm, 'pretendard/dist/LICENSE.txt'), out('fonts/LICENSE-Pretendard.txt'));
let css = '/* Generated by tools/vendor.mjs. Pretendard Variable (OFL-1.1, dynamic subset), JetBrains Mono Variable (OFL-1.1). */\n';
const preCss = fs.readFileSync(path.join(pre, 'pretendardvariable-dynamic-subset.css'), 'utf8');
for (const m of preCss.matchAll(/@font-face\s*{[^}]*}/g)) {
  const file = m[0].match(/woff2-dynamic-subset\/([^)]+\.woff2)/)[1];
  fs.copyFileSync(path.join(pre, 'woff2-dynamic-subset', file), out('fonts/pretendard', file));
  css += m[0].replace('./woff2-dynamic-subset/', 'pretendard/').replace(/\s+/g, ' ') + '\n';
}
const jb = path.join(nm, '@fontsource-variable/jetbrains-mono');
fs.copyFileSync(path.join(jb, 'LICENSE'), out('fonts/LICENSE-JetBrains-Mono.txt'));
for (const sub of ['latin', 'latin-ext']) {
  const file = `jetbrains-mono-${sub}-wght-normal.woff2`;
  fs.copyFileSync(path.join(jb, 'files', file), out('fonts', file));
}
const jbCss = fs.readFileSync(path.join(jb, 'wght.css'), 'utf8');
for (const m of jbCss.matchAll(/@font-face\s*{[^}]*}/g)) {
  const f = m[0].match(/files\/(jetbrains-mono-(latin|latin-ext)-wght-normal\.woff2)/);
  if (!f) continue;
  css += m[0].replace(/src:[^;]+;/, `src: url(${f[1]}) format('woff2-variations');`).replace(/\s+/g, ' ') + '\n';
}
fs.writeFileSync(out('fonts/fonts.css'), css);

// Icons -----------------------------------------------------------------
const icons = [
  'hand-tap', 'check-circle', 'warning-octagon', 'circle-notch', 'pause-circle', 'cloud-slash', 'device-mobile', 'device-tablet', 'laptop', 'watch', 'bell-ringing', 'fingerprint', 'terminal-window',
  'chat-text', 'plugs-connected', 'arrows-left-right', 'squares-four', 'lock-simple', 'cloud', 'wifi-high',
  'check', 'arrow-right', 'arrow-up-right', 'github-logo', 'play', 'pause', 'speaker-simple-x',
  'speaker-simple-high', 'download-simple', 'shield-check', 'hard-drives', 'x', 'globe-simple', 'moon',
  'link-simple', 'info', 'app-store-logo', 'google-play-logo', 'windows-logo', 'apple-logo', 'android-logo', 'sun', 'desktop', 'sparkle', 'flow-arrow', 'git-diff', 'hourglass-medium', 'users-three', 'list-checks', 'envelope-simple',
  'question', 'clock-countdown', 'gauge', 'minus', 'plus', 'flag-checkered', 'arrow-bend-down-right',
];
mkdir(out('icons'));
for (const name of icons) {
  const f = path.join(nm, '@phosphor-icons/core/assets/light', `${name}-light.svg`);
  if (!fs.existsSync(f)) { console.error('missing icon', name); process.exitCode = 1; continue; }
  fs.copyFileSync(f, out('icons', `${name}.svg`));
}
fs.copyFileSync(path.join(nm, '@phosphor-icons/core/LICENSE'), out('icons/LICENSE'));
console.log('vendored fonts and', icons.length, 'icons');
