// Writes the film's brand inputs from the same sources as the site:
//   reel/theme.css  color and font tokens (tools/theme/theme.json)
//   reel/brand.js   Phosphor Light icons, the brand logo SVGs, mockup background colors
//   node brandjs.mjs <path/to/Foreman/docs/design> [mockup-bg.json]
import fs from 'node:fs';
import path from 'node:path';
import { theme, derived } from '../theme/tokens.mjs';

const here = import.meta.dirname;
const design = process.argv[2];
const bg = process.argv[3] && fs.existsSync(process.argv[3]) ? JSON.parse(fs.readFileSync(process.argv[3], 'utf8')) : {};
const first = (...c) => { const f = c.find((x) => fs.existsSync(path.join(design, x))); if (!f) throw new Error('missing ' + c.join(' | ')); return fs.readFileSync(path.join(design, f), 'utf8'); };

// Light tokens drive the light scenes, "night" tokens (the theme's dark values) the dark scenes.
const L = { ...theme.light, ...derived('light') }, D = { ...theme.dark, ...derived('dark') };
const vars = {
  bg: L.paper, surface: L.panel, sunken: L['panel-2'], ink: L.ink, ink2: L['ink-2'], ink3: L.mute, line: L.rule, line2: L['rule-strong'],
  accent: L.accent, 'accent-c': L['accent-container'], 'on-accent-c': L['on-accent-container'],
  signal: L.signal, 'signal-d': D.signal, 'on-signal': L['on-signal'], 'signal-d-rgb': D['signal-rgb'],
  success: L.success, 'success-d': D.success, 'danger-text': L['danger-text'],
  night: D.paper, 'night-1': D.panel, 'night-text': D.ink, 'night-text-rgb': D['ink-rgb'], 'night-2': D['ink-2'], 'night-3': D.mute, 'night-line': D.rule,
  'running-d': D.running, 'shadow-rgb': L['shadow-rgb'],
  display: theme.fonts.sans, mono: theme.fonts.mono,
};
fs.writeFileSync(path.join(here, 'reel/theme.css'), `/* Generated by brandjs.mjs from tools/theme/theme.json (${theme.name}). */\n:root {\n${Object.entries(vars).map(([k, v]) => `  --${k}: ${v};`).join('\n')}\n}\n`);

const icons = path.resolve(here, '../../assets/icons');
const ICONS = {};
for (const f of fs.readdirSync(icons)) if (f.endsWith('.svg')) ICONS[f.slice(0, -4)] = fs.readFileSync(path.join(icons, f), 'utf8').trim();
const SYMBOL = process.env.SYMBOL || 'pulse';
const maybe = (...c) => { const f = c.find((x) => fs.existsSync(path.join(design, x))); return f ? fs.readFileSync(path.join(design, f), 'utf8') : null; };
const LOGO = {
  symbol: first('v3/logo/symbol-black.svg', 'logo/symbol-ink.svg'),
  lockup: first('v3/logo/lockup-black.svg', 'logo/lockup-ink.svg'),
  // the stroke drawing of the mark (before it was outlined), used to draw the mark in the end card
  stroke: maybe(`v3/symbol/${SYMBOL}/mark-black.svg`),
  ink: theme.logo.ink, accent: theme.logo.accent,
};
const MOCKUPS = fs.readdirSync(path.join(here, 'assets/img')).filter((f) => f.endsWith('.png')).map((f) => f.slice(0, -4));
fs.writeFileSync(path.join(here, 'reel/brand.js'), `/* Generated by brandjs.mjs from assets/icons (Phosphor Light, MIT), the Foreman brand logo and the mockups. */
window.ICONS = ${JSON.stringify(ICONS)};
window.LOGO = ${JSON.stringify(LOGO)};
window.MOCKUP_BG = ${JSON.stringify(bg)};
window.MOCKUPS = ${JSON.stringify(MOCKUPS)};
`);
console.log('wrote reel/theme.css and reel/brand.js');
