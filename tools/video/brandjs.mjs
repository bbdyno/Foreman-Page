// Prints reel/brand.js: Phosphor Light icons and the Foreman logo SVGs as strings for the scenes.
import fs from 'node:fs';
import path from 'node:path';
const design = process.argv[2];
const icons = path.resolve(import.meta.dirname, '../../assets/icons');
const theme = JSON.parse(fs.readFileSync(path.resolve(import.meta.dirname, '../theme/theme.json'), 'utf8'));
const ICONS = {};
for (const f of fs.readdirSync(icons)) if (f.endsWith('.svg')) ICONS[f.slice(0, -4)] = fs.readFileSync(path.join(icons, f), 'utf8').trim();
const LOGO = {
  symbol: fs.readFileSync(path.join(design, 'logo/symbol-ink.svg'), 'utf8'),
  lockup: fs.readFileSync(path.join(design, 'logo/lockup-ink.svg'), 'utf8'),
};
process.stdout.write(`/* Generated by brandjs.mjs from assets/icons (Phosphor Light, MIT) and the Foreman brand logo. */
window.ICONS = ${JSON.stringify(ICONS)};
window.LOGO = ${JSON.stringify(LOGO)};
window.THEME = ${JSON.stringify({ light: theme.light, dark: theme.dark })};
`);
